// The feature guides' pages and the app's copy, from website/guides/guides.json. No dependencies.
//   node website/admin/guides.mjs           write
//   node website/admin/guides.mjs --check   exit 1 if out of date (build.mjs runs it, so validate does)
// The pictures are drawn by guides.py from a screens artifact; this checks that each one exists.
//   website/guides/index.md, website/guides/<id>/index.md   the pages (build.mjs makes their index.html)
//   Apps/VoiceDebrief/Resources/vd-guides.json              the app's Guide screens
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SITE = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const REPO = resolve(SITE, '..');
const CHECK = process.argv.includes('--check');
const spec = JSON.parse(readFileSync(join(SITE, 'guides/guides.json'), 'utf8'));
const ideas = JSON.parse(readFileSync(join(SITE, 'ideas/ideas.json'), 'utf8'));
const byId = new Map(ideas.ideas.map((i) => [i.id, i]));
const label = Object.fromEntries(ideas.statuses.map((s) => [s.id, s.label]));
const problems = [];

const files = [];
const app = { about: 'Generated by website/admin/guides.mjs from website/guides/guides.json. Do not edit.', pictures: spec.pictures, guides: [] };
const picturesOf = (g) => (g.app === 'SGit Vaults' && spec.pictures_sgit) || spec.pictures;
for (const g of spec.guides) {
  if (!/^[a-z0-9-]+$/.test(g.id)) problems.push(`guide id ${g.id}`);
  for (const id of g.ideas || []) if (!byId.has(id)) problems.push(`${g.id}: no idea ${id}`);
  const steps = g.steps.map((s, i) => {
    const img = `${g.id}-${i + 1}.jpg`;
    for (const p of [join(SITE, 'guides/img', img), join(REPO, 'Apps/VoiceDebrief/Resources', `vd-guide-${img}`)])
      if (!existsSync(p)) problems.push(`${g.id}: missing picture ${p.slice(REPO.length + 1)} (run website/admin/guides.py)`);
    return { screen: s.screen, caption: s.caption, image: `vd-guide-${g.id}-${i + 1}`, callouts: s.callouts.map((c) => ({ n: c.n, text: c.text })) };
  });
  app.guides.push({ id: g.id, title: g.title, app: g.app, pictures: picturesOf(g), intro: g.intro, ideas: g.ideas || [], steps });
  const related = (g.ideas || []).map((id) => byId.get(id)).filter(Boolean);
  files.push([join(SITE, 'guides', g.id, 'index.md'), `# ${g.title}

${g.intro}

[Every guide](../index.md) · [Ideas and where they stand](../../ideas/index.md)

${g.steps.map((s, i) => `## ${i + 1}. ${s.caption}

![${s.caption} Numbered arrows mark the parts described below.](../img/${g.id}-${i + 1}.jpg)

${s.callouts.map((c) => `${c.n}. ${c.text}`).join('\n')}
`).join('\n')}
${related.length ? `## Where this stands

${related.map((r) => `- ${r.title}: **${label[r.status]}**. ${r.why}`).join('\n')}
` : ''}
*Pictures: ${picturesOf(g)}*
`]);
}
files.push([join(SITE, 'guides/index.md'), `# Guides to every feature

A page per feature, with pictures of the screens and numbered arrows. The same guides are in the app, under Guide. What a feature is and whether it has been seen working is on [Ideas and where they stand](../ideas/index.md); what exists is the [reality file](../built/index.md).

| Guide | App | What it covers |
|---|---|---|
${spec.guides.map((g) => `| [${g.title}](${g.id}/index.md) | ${g.app} | ${g.intro.split('. ')[0].replace(/\.$/, '')}. |`).join('\n')}

*Pictures: ${spec.pictures}${spec.pictures_sgit ? ' ' + spec.pictures_sgit : ''}*
`]);
files.push([join(REPO, 'Apps/VoiceDebrief/Resources/vd-guides.json'), JSON.stringify(app, null, 1) + '\n']);

if (problems.length) { console.error(`guides:\n  ${problems.join('\n  ')}`); process.exit(1); }
const stale = files.filter(([p, s]) => !existsSync(p) || readFileSync(p, 'utf8') !== s).map(([p]) => p.slice(REPO.length + 1));
if (CHECK) {
  if (stale.length) { console.error(`guides: out of date, run node website/admin/guides.mjs:\n  ${stale.join('\n  ')}`); process.exit(1); }
} else for (const [p, s] of files) { mkdirSync(dirname(p), { recursive: true }); writeFileSync(p, s); }
